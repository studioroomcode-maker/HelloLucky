"""
Create/configure the Hello Luck Supabase project via the Management API (idempotent).

Needs in .env:  SUPABASE_ACCESS_TOKEN=sbp_...   (https://supabase.com/dashboard/account/tokens)
Optional:       SUPABASE_ORG=<org slug or id>    SUPABASE_PROJECT_REF=<ref>  (written back after creation)

Does: create project (Seoul) → wait until healthy → apply supabase/*.sql →
enable anonymous sign-in → write the public URL + anon key to src/config/backend.ts.
The access token and DB password stay in .env; only the public anon key goes into the app.
"""
import os
import re
import secrets
import sys
import time
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"
API = "https://api.supabase.com/v1"
DEFAULT_ORG = "sbytlfpufuwfdbtoggiv"


def read_env() -> dict[str, str]:
    out = {}
    for line in ENV.read_text(encoding="utf-8").splitlines() if ENV.exists() else []:
        m = re.match(r"^([A-Z0-9_]+)=(.*)$", line.strip())
        if m:
            out[m.group(1)] = m.group(2)
    return out


def write_env(key: str, value: str) -> None:
    lines = ENV.read_text(encoding="utf-8").splitlines() if ENV.exists() else []
    lines = [l for l in lines if not l.startswith(f"{key}=")] + [f"{key}={value}"]
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")


def call(method: str, path: str, token: str, **kw):
    r = requests.request(method, API + path, headers={"Authorization": f"Bearer {token}"}, timeout=60, **kw)
    if r.status_code >= 400:
        sys.exit(f"❌ {method} {path} → {r.status_code}: {r.text[:500]}")
    return r.json() if r.text else None


def main():
    env = read_env()
    token = env.get("SUPABASE_ACCESS_TOKEN") or os.getenv("SUPABASE_ACCESS_TOKEN")
    if not token:
        sys.exit("❌ .env 에 SUPABASE_ACCESS_TOKEN=sbp_... 를 넣어주세요.")

    ref = env.get("SUPABASE_PROJECT_REF")
    if not ref:
        want = env.get("SUPABASE_ORG", DEFAULT_ORG)
        orgs = call("GET", "/organizations", token)
        org = next((o for o in orgs if want in (o.get("id"), o.get("slug"))), None)
        if not org:
            sys.exit(f"❌ 조직 {want} 을 찾지 못했어요. 보이는 조직: {[(o.get('name'), o.get('id')) for o in orgs]}")
        db_pass = secrets.token_urlsafe(24)
        write_env("SUPABASE_DB_PASSWORD", db_pass)
        project = call("POST", "/projects", token, json={
            "name": "hello-luck", "organization_id": org["id"], "region": "ap-northeast-2", "db_pass": db_pass,
        })
        ref = project["id"]
        write_env("SUPABASE_PROJECT_REF", ref)
        print(f"✅ 프로젝트 생성: {ref}")

    for _ in range(90):
        status = call("GET", f"/projects/{ref}", token).get("status")
        if status == "ACTIVE_HEALTHY":
            break
        print(f"   상태 {status} … 대기")
        time.sleep(10)
    else:
        sys.exit("❌ 프로젝트가 15분 안에 준비되지 않았어요. 잠시 뒤 다시 실행하세요.")

    # schema.sql first, then feature files (all idempotent) in name order.
    files = [ROOT / "supabase" / "schema.sql"] + sorted(p for p in (ROOT / "supabase").glob("*.sql") if p.name != "schema.sql")
    for f in files:
        call("POST", f"/projects/{ref}/database/query", token, json={"query": f.read_text(encoding="utf-8")})
        print(f"✅ {f.name} 적용")

    call("PATCH", f"/projects/{ref}/config/auth", token, json={"external_anonymous_users_enabled": True})
    print("✅ 익명 로그인 켜짐")

    keys = call("GET", f"/projects/{ref}/api-keys", token)
    anon = next(k["api_key"] for k in keys if k.get("name") == "anon")
    url = f"https://{ref}.supabase.co"
    (ROOT / "src" / "config" / "backend.ts").write_text(
        "/** Public Supabase endpoint for the shared map. The anon key is public by design; RLS guards the data.\n"
        " * Generated by scripts/setup_supabase.py. */\n"
        f"export const BACKEND = {{\n  url: '{url}',\n  anonKey: '{anon}',\n}} as const;\n",
        encoding="utf-8",
    )
    print(f"✅ src/config/backend.ts ← {url}")


if __name__ == "__main__":
    main()
